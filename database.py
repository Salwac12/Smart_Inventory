import os
import socket
import sqlite3

from pathlib import Path


# ==========================================
# SMART INVENTORY DATABASE CONFIGURATION
# ==========================================

BASE_DIR = Path(__file__).resolve().parent

DATABASE = BASE_DIR / "inventory.db"

DATABASE_URL = os.environ.get(
    "DATABASE_URL",
    ""
).strip()


# ==========================================
# DATABASE MODE
# ==========================================

def using_postgresql():

    return bool(DATABASE_URL)


# ==========================================
# SQLITE DATABASE INITIALIZATION
# ==========================================

def create_sqlite_database():

    conn = sqlite3.connect(DATABASE)

    try:

        conn.execute("PRAGMA foreign_keys = ON")

        conn.execute("""
            CREATE TABLE IF NOT EXISTS components (

                id INTEGER PRIMARY KEY AUTOINCREMENT,

                part_number TEXT NOT NULL UNIQUE,

                component_name TEXT NOT NULL,

                category TEXT,

                quantity INTEGER NOT NULL DEFAULT 0
                    CHECK (quantity >= 0),

                unit_price REAL NOT NULL DEFAULT 0
                    CHECK (unit_price >= 0),

                supplier TEXT,

                minimum_stock INTEGER NOT NULL DEFAULT 0
                    CHECK (minimum_stock >= 0),

                created_at TIMESTAMP
                    DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS stock_transactions (

                id INTEGER PRIMARY KEY AUTOINCREMENT,

                component_id INTEGER NOT NULL,

                transaction_type TEXT NOT NULL
                    CHECK (transaction_type IN ('IN', 'OUT')),

                quantity INTEGER NOT NULL
                    CHECK (quantity > 0),

                remarks TEXT,

                transaction_date TIMESTAMP
                    DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (component_id)
                    REFERENCES components(id)
            )
        """)

        conn.commit()

        print("SQLite database initialized.")

    except Exception:

        conn.rollback()
        raise

    finally:

        conn.close()


# ==========================================
# POSTGRESQL CONNECTION
# ==========================================

def get_postgres_connection():

    if not using_postgresql():

        raise RuntimeError(
            "DATABASE_URL is not configured."
        )

    import psycopg

    from psycopg.rows import dict_row
    from psycopg.conninfo import conninfo_to_dict

    # Read hostname from the existing Neon URL.
    # Never print the connection string.

    settings = conninfo_to_dict(DATABASE_URL)

    hostname = settings.get("host")

    if not hostname:

        raise RuntimeError(
            "PostgreSQL hostname is missing."
        )

    port = int(settings.get("port") or 5432)

    # Resolve IPv4 addresses only.

    addresses = socket.getaddrinfo(
        hostname,
        port,
        family=socket.AF_INET,
        type=socket.SOCK_STREAM
    )

    if not addresses:

        raise RuntimeError(
            "No IPv4 address found for Neon."
        )

    ipv4_address = addresses[0][4][0]

    # Use the IPv4 address for the network connection.
    # Keep the hostname in DATABASE_URL for TLS/SNI.
    # Do not override Neon's certificate settings.

    conn = psycopg.connect(
        DATABASE_URL,
        hostaddr=ipv4_address,
        row_factory=dict_row,
        connect_timeout=10,
        prepare_threshold=None
    )

    return conn


# ==========================================
# POSTGRESQL DATABASE INITIALIZATION
# ==========================================

def create_postgres_database():

    conn = get_postgres_connection()

    try:

        conn.execute("""
            CREATE TABLE IF NOT EXISTS components (

                id INTEGER GENERATED BY DEFAULT
                    AS IDENTITY PRIMARY KEY,

                part_number TEXT NOT NULL UNIQUE,

                component_name TEXT NOT NULL,

                category TEXT,

                quantity INTEGER NOT NULL DEFAULT 0
                    CHECK (quantity >= 0),

                unit_price NUMERIC(14, 4)
                    NOT NULL DEFAULT 0
                    CHECK (unit_price >= 0),

                supplier TEXT,

                minimum_stock INTEGER NOT NULL DEFAULT 0
                    CHECK (minimum_stock >= 0),

                created_at TIMESTAMP
                    DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS stock_transactions (

                id INTEGER GENERATED BY DEFAULT
                    AS IDENTITY PRIMARY KEY,

                component_id INTEGER NOT NULL,

                transaction_type TEXT NOT NULL
                    CHECK (transaction_type IN ('IN', 'OUT')),

                quantity INTEGER NOT NULL
                    CHECK (quantity > 0),

                remarks TEXT,

                transaction_date TIMESTAMP
                    DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (component_id)
                    REFERENCES components(id)
            )
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS
                idx_stock_transactions_component
            ON stock_transactions(component_id)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS
                idx_stock_transactions_date
            ON stock_transactions(transaction_date)
        """)

        conn.commit()

        print("PostgreSQL database initialized.")

    except Exception:

        conn.rollback()
        raise

    finally:

        conn.close()


# ==========================================
# MAIN DATABASE INITIALIZATION
# ==========================================

def create_database():

    if using_postgresql():

        print("Database mode: PostgreSQL")

        create_postgres_database()

    else:

        print("Database mode: SQLite")

        create_sqlite_database()


# ==========================================
# DIRECT EXECUTION
# ==========================================

if __name__ == "__main__":

    create_database()